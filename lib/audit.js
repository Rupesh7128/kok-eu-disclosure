import PDFDocument from "pdfkit";
import { brand } from "./brand.js";
import { escHtml } from "./input.js";
import { itemsFor, CHECKLIST_HEADER } from "./checklist.js";

const { orange, ink, paper } = brand.colors;

function grouped(contentTypes) {
  const out = [];
  for (const it of itemsFor(contentTypes)) {
    let g = out.find((x) => x.section === it.section);
    if (!g) out.push((g = { section: it.section, items: [] }));
    g.items.push(it);
  }
  return out;
}

export function checklistHtml(cfg) {
  const groups = grouped(cfg.contentTypes);
  const body = groups.map((g) => `<section><h2>${escHtml(g.section)}</h2>
${g.items.map((i) => `<div class="item"><span class="box" aria-hidden="true"></span><div><b>${i.id}</b> <span class="ref">${escHtml(i.ref)}</span><p>${escHtml(i.text)}</p><p class="note">Evidence / owner / date: ____________________________</p></div></div>`).join("\n")}
</section>`).join("\n");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${escHtml(CHECKLIST_HEADER.title)} — ${escHtml(cfg.siteName)}</title>
<style>
body{margin:0;background:${paper};color:${ink};font:15px/1.5 system-ui,-apple-system,"Segoe UI",sans-serif}
main{max-width:50rem;margin:0 auto;padding:32px 24px}
h1{font:400 34px/1.1 Georgia,serif;margin:0 0 8px}
h2{font:700 13px/1.3 system-ui,sans-serif;letter-spacing:.08em;text-transform:uppercase;color:${orange};border-top:2px solid ${ink};padding-top:10px;margin:28px 0 8px}
.meta,.note{font-size:13px;color:${ink};opacity:.75}
.warn{border:2px solid ${ink};padding:10px 14px;margin:16px 0;background:${paper}}
.item{display:flex;gap:12px;padding:10px 0;border-bottom:1px solid ${ink}33;break-inside:avoid}
.box{flex:none;width:16px;height:16px;border:2px solid ${ink};margin-top:3px}
.item p{margin:2px 0}.ref{font:12px ui-monospace,monospace;color:${orange}}
@media print{body{background:#fff}main{padding:0}}
</style></head><body><main>
<h1>${escHtml(CHECKLIST_HEADER.title)}</h1>
<p class="meta">Site: <b>${escHtml(cfg.siteName)}</b>${cfg.botName ? ` · Assistant: <b>${escHtml(cfg.botName)}</b>` : ""} · Content types: ${escHtml(cfg.contentTypes.join(", "))}<br>Reviewer: ______________________ Date: ______________</p>
<div class="warn"><b>${escHtml("Tooling for transparency obligations; not legal advice.")}</b> ${escHtml(CHECKLIST_HEADER.disclaimer.replace("Tooling for transparency obligations; not legal advice. ", ""))}</div>
${body}
<p class="meta">Generated by the EU AI Act Art. 50 Disclosure Pack, ${escHtml(brand.name)}, ${escHtml(brand.person)}. Print this page to PDF from your browser if you prefer.</p>
</main></body></html>
`;
}

export function checklistPdf(cfg) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 54, info: { Title: `${CHECKLIST_HEADER.title} — ${cfg.siteName}`, Author: brand.name } });
    const chunks = [];
    doc.on("data", (c) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
    const W = doc.page.width - 108;
    const bg = () => doc.rect(0, 0, doc.page.width, doc.page.height).fill(paper);
    bg();
    doc.on("pageAdded", bg);
    const ensure = (h) => { if (doc.y + h > doc.page.height - 60) doc.addPage(); };

    doc.fillColor(ink).font("Times-Roman").fontSize(24).text(CHECKLIST_HEADER.title, 54, 54, { width: W });
    doc.moveDown(0.4).font("Helvetica").fontSize(10)
      .text(`Site: ${cfg.siteName}${cfg.botName ? `   Assistant: ${cfg.botName}` : ""}   Content types: ${cfg.contentTypes.join(", ")}`, { width: W })
      .text("Reviewer: ______________________    Date: ______________", { width: W });
    doc.moveDown(0.6);
    const y0 = doc.y;
    const warn = CHECKLIST_HEADER.disclaimer;
    const wh = doc.heightOfString(warn, { width: W - 16 }) + 16;
    doc.lineWidth(1.5).strokeColor(ink).rect(54, y0, W, wh).stroke();
    doc.fillColor(ink).font("Helvetica-Bold").fontSize(9).text(warn, 62, y0 + 8, { width: W - 16 });
    doc.y = y0 + wh + 14;

    for (const g of grouped(cfg.contentTypes)) {
      ensure(60);
      doc.moveDown(0.5).fillColor(orange).font("Helvetica-Bold").fontSize(9).text(g.section.toUpperCase(), 54, doc.y, { width: W, characterSpacing: 0.8 });
      doc.moveTo(54, doc.y + 2).lineTo(54 + W, doc.y + 2).lineWidth(1.5).strokeColor(ink).stroke();
      doc.moveDown(0.6);
      for (const it of g.items) {
        const th = doc.font("Helvetica").fontSize(10).heightOfString(it.text, { width: W - 28 });
        ensure(th + 36);
        const y = doc.y;
        doc.lineWidth(1.5).strokeColor(ink).rect(54, y + 2, 11, 11).stroke();
        doc.fillColor(orange).font("Helvetica-Bold").fontSize(8).text(`${it.id}  ${it.ref}`, 74, y + 2, { width: W - 20 });
        doc.fillColor(ink).font("Helvetica").fontSize(10).text(it.text, 74, doc.y + 1, { width: W - 20 });
        doc.fillColor(ink).opacity(0.55).fontSize(8).text("Evidence / owner / date: ______________________________", 74, doc.y + 3, { width: W - 20 }).opacity(1);
        doc.moveDown(0.6);
      }
    }
    ensure(40);
    doc.moveDown(0.5).fillColor(ink).opacity(0.7).font("Helvetica").fontSize(8)
      .text(`Generated by the EU AI Act Art. 50 Disclosure Pack, ${brand.name}, ${brand.person}. ${brand.url}`, 54, doc.y, { width: W }).opacity(1);
    doc.end();
  });
}
